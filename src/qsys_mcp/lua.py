def check_syntax(code: str) -> dict:
    """Parse Lua (5.3 grammar, as used by Q-SYS). Returns ok/error plus light lint warnings."""
    try:
        tree = lua_ast.parse(code)
    except Exception as e:  # luaparser raises SyntaxException with a readable message
        return {"ok": False, "error": str(e).strip()}
    return {"ok": True, "warnings": _lint(tree, code)}


def _lint(tree, code: str) -> list[str]:
    warnings = []
    assigned_globals, local_names = set(), set()
    for node in lua_ast.walk(tree):
        if isinstance(node, lua_ast.LocalAssign):
            local_names.update(t.id for t in node.targets if isinstance(t, lua_ast.Name))
        elif isinstance(node, lua_ast.LocalFunction) and isinstance(node.name, lua_ast.Name):
            local_names.add(node.name.id)
        elif isinstance(node, lua_ast.Assign):
            for t in node.targets:
                if isinstance(t, lua_ast.Name):
                    assigned_globals.add(t.id)
    implicit = sorted(assigned_globals - local_names - QSYS_GLOBALS)
    if implicit:
        warnings.append(f"Assigned without 'local' (implicit globals): {', '.join(implicit)}")
    if re.search(r"\bwhile\s+true\s+do\b", code) and "Timer" not in code:
        warnings.append("'while true do' loop: Q-SYS scripts are event-driven; a busy loop will starve the script. Use Timer instead.")
    if re.search(r"\bos\.execute\b|\bio\.popen\b", code):
        warnings.append("os.execute/io.popen are not available in Q-SYS.")
    return warnings


